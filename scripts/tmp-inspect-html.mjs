import fs from "node:fs";
const html = fs.readFileSync("/tmp/dash.html", "utf8");
const i = html.indexOf("</head>");
const head = html.slice(0, i);
console.log("head length:", head.length);
const scripts = head.match(/<script[^>]*>/g) || [];
console.log("script tags in head:", scripts.length);
for (const s of scripts) console.log(s.slice(0, 200));
const links = head.match(/<link[^>]*theme-init[^>]*>/g) || [];
console.log("theme-init links:", links);
const idx = html.indexOf("theme-init.js");
console.log("context:", html.slice(idx - 120, idx + 200));
